#!/usr/bin/env python3
"""Writes src/bars_data.h from WISH.EXE (Majic 12, 1993): the data blob of part 18,
0x296 bytes at file offset 58691h (the code blob follows at 58927h).

  tools/extract.py ~/proy/rea/wish/WISH.EXE src/bars_data.h
"""
import struct
import sys

OFF, LEN = 0x58691, 0x296
exe = open(sys.argv[1], 'rb').read()
assert len(exe) == 774795, 'not the 774795-byte WISH.EXE'
d = exe[OFF:OFF + LEN]


def rows(vals, per, fmt):
    return ',\n'.join('    ' + ', '.join(fmt % v for v in vals[i:i + per]) for i in range(0, len(vals), per))


pal = d[9:0x39]                                  # DAC colours 1-16, 6-bit RGB
bar = d[0x39:0x49]                               # the 16 pixels of a bar
sine = struct.unpack_from('<256H', d, 0x49)      # 50 + 50 sin, 0-100
sets = [struct.unpack_from('<6H', d, 0x249 + 12 * k) for k in range(4)]
out = ['// Generated by tools/extract.py from WISH.EXE (part 18 data, file offset 58691h).',
       '#pragma once', '#include <cstdint>', '', 'namespace wb {', '',
       '// DAC colours 1-16 (6-bit R, G, B): a dark-to-white red ramp, then white-to-dark green',
       'constexpr uint8_t kPalette[48] = {', rows(list(pal), 12, '0x%02x'), '};', '',
       '// one bar: colours 1-16 left to right', 'constexpr uint8_t kBar[16] = {',
       rows(list(bar), 16, '%d'), '};', '',
       '// 256 steps of a sine, 0-100 (floor(50 + 50 sin), except entry 128, which is 49)',
       'constexpr uint16_t kSine[256] = {', rows(list(sine), 16, '%3d'), '};', '',
       '// the 4 motions: per-line phase steps of the 3 sines, then per-frame steps (mod 256)',
       'constexpr uint16_t kSets[4][6] = {',
       ',\n'.join('    {' + ', '.join('%d' % v for v in s) + '}' for s in sets), '};', '',
       '}  // namespace wb', '']
open(sys.argv[2], 'w').write('\n'.join(out))
