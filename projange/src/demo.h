// The demo as the programs ANGEL.EXE's loader runs, one after the other.
// Each program is translated to C++ and runs on the machine's memory where
// DOS put it (the harness's addresses); the resident ones leave interrupt
// handlers (Machine::vec) behind for the rest:
//
//   0  DRIVERS.VGA #1  the video setup: checks the BIOS against SETUP's
//                      CRC, the VGA driver (int FBh), resident
//   1  DRIVERS.VGA #2  the music player (int FFh, the PIT, the GUS), resident
//   2  ANGEL.EXE #1    the XMS stub: 2155 KB of XMS, unreal mode, int FCh, resident
//   3  ANGEL.EXE #2    the module loader (int FAh): file to XMS, decrypting, resident
//   4  ...             the parts (see parts.h)
#pragma once

#include <cstdint>
#include <functional>
#include <memory>
#include <string>
#include <vector>

#include "dos.h"
#include "loader.h"
#include "machine.h"

namespace angel {

// a program's int 21h/4Ch or /31h: back to the loader
struct ProgramEnd {};

class Cpu;

class Demo {
public:
    Demo(Machine& m, std::vector<uint8_t> angelExe, std::vector<uint8_t> driversVga);
    ~Demo();
    // the loader's main (CS:0100h): to the end (int 21h/4Ch)
    void main();

    Machine& m;
    Dos dos;
    std::unique_ptr<Cpu> cpu;

    // the running program: its PSP, where it starts
    uint16_t psp = 0;
    Entry entry{};
    int index = -1;                     // which program (0, 1, ...)
    // int 21h/4Ch, /31h from a program
    [[noreturn]] void exitProgram(uint8_t code, int residentParas = -1);
    // int 10h AH=0
    void setMode(uint8_t mode);
    // what the programs write to DOS's screen (int 21h/40h): the end's text
    std::string text;

private:
    uint16_t loaderRun();               // CS:016Eh: one program
    void loaderModule();                // CS:0150h: one module through int FCh, FAh
    int curHandle_ = 0;                 // [6C0h]
    int drvHandle_ = 0, exeHandle_ = 0;
};

// The programs themselves are translated from the code the harness ran
// (code*.cpp, generated by the analysis's translate.py), each registered
// with Cpu under its index.

}  // namespace angel
