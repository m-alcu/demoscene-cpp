#!/usr/bin/env python3
"""Pulls the end part of HEX APPEAL and its music out of APPEAL.EXE.

    python3 -I tools/extract_assets.py <APPEAL.EXE> <project dir>

APPEAL.EXE is a chain of MZ executables followed by the module: the loader
with the music system, the setup, five demo parts, then LIBERTINE (a 6
channel ProTracker module) and the setup's RIX pictures. The end part is the
seventh executable; its offsets below are in its load image (after the
512-byte header), and the segments are the ones its relocations name.

Writes:
  assets/libertine.mod  the module, unchanged
  assets/font.bmp       53 glyphs of 24x25, one under another (seg 04E5h)
  assets/marble.bmp     the two 50x42 marble tiles, one under the other (seg 0CE5h)
  assets/palette.dac    the 256 colours, 6-bit, as the part sets them up
  assets/texts.txt      the scroll text, one line per text line
  src/data/tables.h     sine table, character set and glyph widths
"""

import struct
import sys
from pathlib import Path


def mz_chain(exe):
    out, o = [], 0
    while exe[o:o + 2] == b'MZ':
        cblp, cp = struct.unpack_from('<HH', exe, o + 2)
        size = (cp - 1) * 512 + (cblp or 512)
        out.append((o, size))
        o += size
    return out, o


def write_bmp(path, w, h, pix, dac):
    stride = (w + 3) & ~3
    pal = b''.join(bytes(((dac[i * 3 + 2] * 255 + 31) // 63, (dac[i * 3 + 1] * 255 + 31) // 63,
                          (dac[i * 3] * 255 + 31) // 63, 0)) for i in range(256))
    rows = b''.join(pix[y * w:(y + 1) * w] + bytes(stride - w) for y in range(h - 1, -1, -1))
    off = 14 + 40 + 1024
    hdr = b'BM' + struct.pack('<IHHI', off + len(rows), 0, 0, off)
    hdr += struct.pack('<IiiHHIIiiII', 40, w, h, 1, 8, 0, len(rows), 2835, 2835, 256, 256)
    path.write_bytes(hdr + pal + rows)


def main():
    exe = Path(sys.argv[1]).read_bytes()
    root = Path(sys.argv[2])
    chain, end = mz_chain(exe)
    assert len(chain) == 7, 'expected the loader, the setup and five parts'
    o, size = chain[6]
    code = exe[o + 512:o + size]

    # the module: 31 samples, 6CHN, patterns up to the highest in the order list
    mod = exe[end:]
    assert mod[1080:1084] == b'6CHN'
    npat = max(mod[952:1080]) + 1
    total = 1084 + npat * 64 * 6 * 4
    total += sum(struct.unpack_from('>H', mod, 20 + 30 * i + 22)[0] * 2 for i in range(31))
    (root / 'assets').mkdir(exist_ok=True)
    (root / 'assets/libertine.mod').write_bytes(mod[:total])

    # palette: 768 bytes at 4967h, colours C0h..FFh replaced from 0CB5h:0240h
    dac = bytearray(code[0x4967:0x4967 + 768])
    dac[0x240:0x300] = code[0xCB50 + 0x240:0xCB50 + 0x300]
    (root / 'assets/palette.dac').write_bytes(dac)

    charset = code[0x3342:0x3378]           # 53 characters and a 0
    widths = code[0x3378:0x33AE]
    nglyph = len(charset) - 1
    font = code[0x4E50:0x4E50 + nglyph * 600]
    write_bmp(root / 'assets/font.bmp', 24, 25 * nglyph, font, dac)
    marble = code[0xCE50:0xCE50 + 2 * 0x834]
    assert len(marble) == 2 * 0x834
    write_bmp(root / 'assets/marble.bmp', 50, 84, marble, dac)

    text = code[0x1829:code.index(b'\xff', 0x1829)]
    lines = text.split(b'\0')
    assert lines[-1] == b''
    (root / 'assets/texts.txt').write_bytes(b''.join(l + b'\n' for l in lines[:-1]))

    sine = struct.unpack_from('<512h', code, 0x446A)
    h = ['// Generated by tools/extract_assets.py from APPEAL.EXE (end part). Do not edit.',
         '#pragma once', '#include <cstdint>', '', 'namespace hex {', '',
         '// 446Ah: 512 steps of a cosine, amplitude 32767',
         'constexpr int16_t kSine[512] = {']
    for i in range(0, 512, 12):
        h.append('    ' + ', '.join(str(v) for v in sine[i:i + 12]) + ',')
    h += ['};', '',
          '// 3342h: the characters of the font, in glyph order (CP437)',
          'constexpr uint8_t kCharset[%d] = {' % nglyph,
          '    ' + ', '.join('0x%02X' % b for b in charset[:nglyph]), '};',
          '// 3378h: each glyph\'s advance, less the one pixel between letters',
          'constexpr uint8_t kGlyphWidth[%d] = {' % nglyph,
          '    ' + ', '.join(str(b) for b in widths[:nglyph]), '};', '',
          'constexpr int kGlyphs = %d;' % nglyph, '', '}  // namespace hex', '']
    (root / 'src/data').mkdir(parents=True, exist_ok=True)
    (root / 'src/data/tables.h').write_text('\n'.join(h))
    print('module %d bytes, %d text lines, %d glyphs' % (total, len(lines) - 1, nglyph))


if __name__ == '__main__':
    main()
