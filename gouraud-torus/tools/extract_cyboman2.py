#!/usr/bin/env python3
"""Extract the torus of Cyboman 2 (Complex, The Party '94) into src/cyboman2_torus.inc.

  extract_cyboman2.py CYBOMAN2_IMG RAW_420 RAW_1470

CYBOMAN2_IMG: the unpacked intro image (rea/cyboman2-analisis/cyboman2.img).
RAW_420, RAW_1470: screen + DAC dumps of frames 420 and 1470 (6 s and 21 s), from the
cyboman2 port:  CYBOMAN2_RAW=420,1470 cyboman2 --dump DIR --frames 1480

The model is at image offset 594A0h (segment 594Ah, object slot CS:17FDh): header
nv, nf, vertex offset, face offset, normal offset; 576 vertices and normals (3 x int16,
normals of length 127) and 1152 faces (flags, v0, v1, v2). The face flags are 0 in the file;
the intro sets them at run time, and they select the material (see torus.cpp).
Colours: the torus draws with palette indices 100-159 (flag 0) and 164-223 (flag 1).
"""
import struct, sys, os

img = open(sys.argv[1], 'rb').read()
p = 0x594A0
nv, nf, vo, fo, no = struct.unpack_from('<5H', img, p)
assert (nv, nf) == (576, 1152), (nv, nf)
V = [struct.unpack_from('<3h', img, p + vo + 6 * i) for i in range(nv)]
N = [struct.unpack_from('<3h', img, p + no + 6 * i) for i in range(nv)]
F = [struct.unpack_from('<4H', img, p + fo + 8 * i)[1:] for i in range(nf)]

def pal(path):
    d = open(path, 'rb').read()[64000:64768]
    return [tuple(d[3 * i:3 * i + 3]) for i in range(100, 224)]

pals = [pal(sys.argv[2]), pal(sys.argv[3])]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../src/cyboman2_torus.inc')
with open(out, 'w') as f:
    f.write('// The torus of Cyboman 2 (Complex, The Party \'94), generated by tools/extract_cyboman2.py.\n')
    f.write('// Model from the intro image at 594A0h; palettes from the DAC at 6 s and 21 s.\n\n')
    f.write('constexpr int kCybVerts = %d, kCybFaces = %d;\n\n' % (nv, nf))
    def arr(name, typ, rows):
        f.write('static const %s %s[][3] = {\n' % (typ, name))
        for k in range(0, len(rows), 4):
            f.write('    ' + ' '.join('{%d, %d, %d},' % r for r in rows[k:k + 4]) + '\n')
        f.write('};\n\n')
    arr('kCybPos', 'int16_t', V)
    arr('kCybNrm', 'int16_t', N)
    arr('kCybTri', 'uint16_t', F)
    f.write('// DAC entries 100-223 (6-bit), as set when the torus is on screen.\n')
    arr('kCybPalRings', 'uint8_t', pals[0])
    arr('kCybPalSawtooth', 'uint8_t', pals[1])
print('wrote', out, nv, 'verts', nf, 'faces')
